import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const RUNTIME_ASSETS = Object.freeze([
  "app.js", "engine.js", "feedback-diagnostics.js", "feedback-form.js", "index.html", "state-codec.js",
  "style.css", "data/materials.json", "data/nozzles.json", "data/printers.json",
  "locales/da.json", "locales/en.json",
]);

export async function buildRelease(root, assets = RUNTIME_ASSETS) {
  const hash = createHash("sha256");
  for (const relative of [...assets].sort()) {
    hash.update(relative); hash.update("\0");
    hash.update(await readFile(path.join(root, relative))); hash.update("\0");
  }
  const assetFingerprint = hash.digest("hex");
  return { appVersion: `web-${assetFingerprint.slice(0, 12)}`, releaseId: assetFingerprint, assetFingerprint };
}

function sourceFor(release) {
  return `// Generated by scripts/gen-release-manifest.mjs — do not edit.\n` +
    `globalThis.__3DPA_RELEASE__ = Object.freeze(${JSON.stringify(release, null, 2)});\n`;
}

export async function writeOrCheckManifest(root, assets = RUNTIME_ASSETS, check = false) {
  const output = sourceFor(await buildRelease(root, assets));
  const target = path.join(root, "release-manifest.js");
  if (check) {
    let current = "";
    try { current = await readFile(target, "utf8"); } catch {}
    if (current !== output) throw new Error("release_manifest_stale");
    return;
  }
  await writeFile(target, output);
}

const invoked = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invoked) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  try { await writeOrCheckManifest(root, RUNTIME_ASSETS, process.argv.includes("--check")); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
